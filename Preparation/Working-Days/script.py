"""Working Days: count working days between two dates and / or add N working
days to a date, skipping weekends and public holidays.

Holidays are generated by rule for England and Wales, Scotland, Northern
Ireland or the US (federal), including the UK one-off holidays since 2011,
and you can add your own closure dates. If both an end date and a number of
days are given, the block also says whether the end date met the target
(an SLA check).
"""
import datetime as dt
import re

import numpy as np
import pandas as pd
from omniscope.api import OmniscopeApi

omniscope_api = OmniscopeApi()


def opt(name, default=None):
    v = omniscope_api.get_option(name)
    return default if v is None or v == "" else v


start_field = opt("start_field")
end_field = opt("end_field")
days_field = opt("days_field")
days_constant = opt("days_constant", 0)
region = opt("region", "ENGLAND_WALES")
custom_holidays = opt("custom_holidays", "")
weekend = opt("weekend", "SAT_SUN")
include_start = opt("include_start", True)
day_first = opt("day_first", True)

df = omniscope_api.read_input_records(input_number=0)
if df is None:
    omniscope_api.abort("Connect the data to the input.")
for f, label in ((start_field, "start date"),):
    if not f or f not in df.columns:
        omniscope_api.abort(f"Choose the {label} field (got '{f}').")
for f in (end_field, days_field):
    if f and f not in df.columns:
        omniscope_api.abort(f"Field '{f}' is not in the input.")


# ------------------------------------------------------------- holidays
def easter(y):
    a, b, c = y % 19, y // 100, y % 100
    d, e = b // 4, b % 4
    f = (b + 8) // 25
    g = (b - f + 1) // 3
    h = (19 * a + b - d - g + 15) % 30
    i, k = c // 4, c % 4
    l_ = (32 + 2 * e + 2 * i - h - k) % 7
    m = (a + 11 * h + 22 * l_) // 451
    month = (h + l_ - 7 * m + 114) // 31
    day = (h + l_ - 7 * m + 114) % 31 + 1
    return dt.date(y, month, day)


def nth_weekday(y, month, weekday, n):
    """n-th (1-based) weekday (Mon=0) of a month; n=-1 for the last."""
    if n > 0:
        d = dt.date(y, month, 1)
        d += dt.timedelta(days=(weekday - d.weekday()) % 7)
        return d + dt.timedelta(weeks=n - 1)
    d = dt.date(y + (month == 12), month % 12 + 1, 1) - dt.timedelta(days=1)
    return d - dt.timedelta(days=(d.weekday() - weekday) % 7)


def uk_substitutes(days):
    """Move holidays on a weekend to the next free weekday (UK rule)."""
    out, taken = [], set()
    for d, name in days:
        if d.weekday() >= 5:
            s = d
            while s.weekday() >= 5 or s in taken or any(s == x for x, _ in days if x != d):
                s += dt.timedelta(days=1)
            out.append((s, f"{name} (substitute day)"))
            taken.add(s)
        else:
            out.append((d, name))
            taken.add(d)
    return out


UK_ONE_OFF = {  # changes announced by the UK government (gov.uk/bank-holidays)
    2011: {"add": [(dt.date(2011, 4, 29), "Royal wedding")]},
    2012: {"move": {"Spring bank holiday": dt.date(2012, 6, 4)}, "add": [(dt.date(2012, 6, 5), "Queen's Diamond Jubilee")]},
    2020: {"move": {"Early May bank holiday": dt.date(2020, 5, 8)}},
    2022: {"move": {"Spring bank holiday": dt.date(2022, 6, 2)},
           "add": [(dt.date(2022, 6, 3), "Platinum Jubilee bank holiday"), (dt.date(2022, 9, 19), "State Funeral of Queen Elizabeth II")]},
    2023: {"add": [(dt.date(2023, 5, 8), "Coronation of King Charles III")]},
}


def uk_year(y, nation):
    e = easter(y)
    fixed = [(dt.date(y, 1, 1), "New Year's Day")]
    if nation == "SCOTLAND":
        fixed.append((dt.date(y, 1, 2), "2nd January"))
    if nation == "NI":
        fixed.append((dt.date(y, 3, 17), "St Patrick's Day"))
        fixed.append((dt.date(y, 7, 12), "Battle of the Boyne (Orangemen's Day)"))
    if nation == "SCOTLAND":
        fixed.append((dt.date(y, 11, 30), "St Andrew's Day"))
    fixed += [(dt.date(y, 12, 25), "Christmas Day"), (dt.date(y, 12, 26), "Boxing Day")]
    days = uk_substitutes(sorted(fixed))
    days.append((e - dt.timedelta(days=2), "Good Friday"))
    if nation != "SCOTLAND":
        days.append((e + dt.timedelta(days=1), "Easter Monday"))
    moved = UK_ONE_OFF.get(y, {}).get("move", {})
    early = moved.get("Early May bank holiday", nth_weekday(y, 5, 0, 1))
    spring = moved.get("Spring bank holiday", nth_weekday(y, 5, 0, -1))
    summer = nth_weekday(y, 8, 0, 1) if nation == "SCOTLAND" else nth_weekday(y, 8, 0, -1)
    days += [(early, "Early May bank holiday"), (spring, "Spring bank holiday"), (summer, "Summer bank holiday")]
    days += UK_ONE_OFF.get(y, {}).get("add", [])
    return days


def us_year(y):
    def observed(d, name):
        if d.weekday() == 5:
            return d - dt.timedelta(days=1), f"{name} (observed)"
        if d.weekday() == 6:
            return d + dt.timedelta(days=1), f"{name} (observed)"
        return d, name
    days = [observed(dt.date(y, 1, 1), "New Year's Day"),
            (nth_weekday(y, 1, 0, 3), "Martin Luther King Jr. Day"),
            (nth_weekday(y, 2, 0, 3), "Washington's Birthday"),
            (nth_weekday(y, 5, 0, -1), "Memorial Day")]
    if y >= 2021:
        days.append(observed(dt.date(y, 6, 19), "Juneteenth"))
    days += [observed(dt.date(y, 7, 4), "Independence Day"), (nth_weekday(y, 9, 0, 1), "Labor Day"),
             (nth_weekday(y, 10, 0, 2), "Columbus Day"), observed(dt.date(y, 11, 11), "Veterans Day"),
             (nth_weekday(y, 11, 3, 4), "Thanksgiving Day"), observed(dt.date(y, 12, 25), "Christmas Day")]
    return days


def holidays_for(years):
    rows = []
    for y in years:
        if region == "NONE":
            continue
        days = us_year(y) if region == "US" else uk_year(y, {"ENGLAND_WALES": "EW", "SCOTLAND": "SCOTLAND", "NI": "NI"}[region])
        rows += [(d, n, region) for d, n in days]
    return rows


# --------------------------------------------------------------- dates
def to_date(s):
    if pd.api.types.is_datetime64_any_dtype(s):
        d = s
    else:
        txt = s.astype(object).where(s.notna(), None).astype(str).str.strip()
        iso = txt.str.match(r"^\d{4}-\d{1,2}-\d{1,2}")
        d = pd.Series(pd.NaT, index=s.index, dtype="datetime64[ns]")
        if iso.any():
            d[iso] = pd.to_datetime(txt[iso], errors="coerce", format="mixed")
        rest = ~iso & s.notna()
        if rest.any():
            d[rest] = pd.to_datetime(txt[rest], errors="coerce", dayfirst=bool(day_first), format="mixed")
    if getattr(d.dt, "tz", None) is not None:
        d = d.dt.tz_localize(None)
    return d.dt.normalize()


start = to_date(df[start_field])
end = to_date(df[end_field]) if end_field else None
if days_field:
    ndays = pd.to_numeric(df[days_field], errors="coerce")
elif days_constant:
    ndays = pd.Series(float(days_constant), index=df.index)
else:
    ndays = None
if end is None and ndays is None:
    omniscope_api.abort("Choose an end date field (to count working days) and / or a number of working days to add.")

custom = []
for tok in re.split(r"[,;\n]+", custom_holidays or ""):
    tok = tok.strip()
    if tok:
        d = to_date(pd.Series([tok], dtype=object)).iloc[0]
        if pd.isna(d):
            omniscope_api.abort(f"'{tok}' in the custom holidays is not a date.")
        custom.append((d.date(), "Custom closure", "CUSTOM"))

all_dates = pd.concat([start] + ([end] if end is not None else [])).dropna()
if len(all_dates):
    y0, y1 = all_dates.min().year - 1, all_dates.max().year + 2
else:
    y0 = y1 = dt.date.today().year
hol = holidays_for(range(y0, y1 + 1)) + custom
weekmask = {"SAT_SUN": "1111100", "FRI_SAT": "1111001", "SUN": "1111110", "NONE": "1111111"}[weekend]
hol_dates = np.array(sorted({d for d, _, _ in hol}), dtype="datetime64[D]")
cal = np.busdaycalendar(weekmask=weekmask, holidays=hol_dates)

out = df.copy()
s_ok = start.notna().to_numpy()
s64 = start.to_numpy(dtype="datetime64[D]")
is_wd = np.zeros(len(df), dtype=bool)
is_wd[s_ok] = np.is_busday(s64[s_ok], busdaycal=cal)
out["Start Is Working Day"] = np.where(s_ok, np.where(is_wd, "Yes", "No"), None)

if end is not None:
    e_ok = end.notna().to_numpy() & s_ok
    e64 = end.to_numpy(dtype="datetime64[D]")
    cnt = np.full(len(df), np.nan)
    lo = np.minimum(s64[e_ok], e64[e_ok])
    hi = np.maximum(s64[e_ok], e64[e_ok])
    c = np.busday_count(lo, hi + np.timedelta64(1, "D"), busdaycal=cal).astype(float)
    if not include_start:
        c -= np.is_busday(lo, busdaycal=cal)
    sign = np.where(e64[e_ok] >= s64[e_ok], 1, -1)
    cnt[e_ok] = c * sign
    out["Working Days"] = pd.array(cnt, dtype="Float64").astype("Int64")
    cal_days = np.full(len(df), np.nan)
    cal_days[e_ok] = (e64[e_ok] - s64[e_ok]).astype(float)
    out["Calendar Days"] = pd.array(cal_days, dtype="Float64").astype("Int64")

if ndays is not None:
    n_ok = s_ok & ndays.notna().to_numpy()
    due = np.full(len(df), np.datetime64("NaT", "D"), dtype="datetime64[D]")
    n_int = np.round(ndays.to_numpy(dtype=float)[n_ok]).astype(int)
    due[n_ok] = np.busday_offset(s64[n_ok], n_int, roll="forward", busdaycal=cal)
    out["Due Date"] = pd.to_datetime(due).tz_localize("UTC")
    if end is not None:
        met = np.full(len(df), None, dtype=object)
        both = n_ok & end.notna().to_numpy()
        met[both] = np.where(e64[both] <= due[both], "Yes", "No")
        out["Met Target"] = met
        late = np.full(len(df), np.nan)
        late[both] = np.where(e64[both] > due[both],
                              np.busday_count(due[both], e64[both], busdaycal=cal), 0).astype(float)
        out["Working Days Late"] = pd.array(late, dtype="Float64").astype("Int64")

cal_df = pd.DataFrame(sorted(hol), columns=["Date", "Holiday", "Region"])
cal_df["Date"] = pd.to_datetime(cal_df["Date"]).dt.tz_localize("UTC")
cal_df["Weekday"] = cal_df["Date"].dt.day_name()

omniscope_api.write_output(out, "result")
omniscope_api.write_output(cal_df, "holidays")
msg = f"{int(s_ok.sum()):,} rows; {len(cal_df):,} holidays {y0} to {y1} ({region.replace('_', ' ').title()})"
if "Met Target" in out.columns:
    msg += f"; {(out['Met Target'] == 'Yes').sum():,} met the target"
omniscope_api.close(msg + ".")
